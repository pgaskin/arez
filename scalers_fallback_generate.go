func main() {
	funcs := template.FuncMap{"mul": func(a, b int) int { return a * b }}
	t := template.Must(template.New("scalers").Funcs(funcs).Parse(scalers))
	var b bytes.Buffer
	if err := t.Execute(&b, taps); err != nil {
		fmt.Fprintf(os.Stderr, "error: %v\n", err)
		os.Exit(1)
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		fmt.Fprintf(os.Stderr, "error: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile("scalers_fallback.go", src, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "error: %v\n", err)
		os.Exit(1)
	}
}
